"""Write OVERVIEW.md and overview.csv into the models folder: every model's saved real-hand runs from all sessions,
combined where comparable (rules: results_rules.py). The same table as the W&B leaderboard of upload_wandb.py,
without W&B. Standard library only:

    python3 overview.py [--models-dir ~/policies/real_test]
"""

import argparse
import csv
import os
import statistics
from pathlib import Path

from results_rules import MAX_START_C, load_models, number, saved_runs


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--models-dir", default=os.path.expanduser("~/policies/real_test"))
    root = Path(p.parse_args().models_dir)
    models = load_models(root)
    runs = saved_runs(root)
    by_model = {}
    for r in runs:
        if r.comparable:
            by_model.setdefault(r.model, []).append(r)

    table = []
    for name, m in models.items():
        rs = by_model.get(name, [])
        turns = [number(r.row["turns"]) or 0.0 for r in rs]
        currents = [c for c in (number(r.row.get("total_current_a")) for r in rs) if c is not None]
        table.append(dict(
            model=name, description=m.get("description", ""), goal=m["goal"], runs=len(rs),
            mean_turns=round(statistics.mean(turns), 1) if turns else "",
            std_turns=round(statistics.stdev(turns), 1) if len(turns) > 1 else "",
            best_turns=round(max(turns), 1) if turns else "", worst_turns=round(min(turns), 1) if turns else "",
            full_60s=f"{sum(r.row['outcome'] == 'completed' for r in rs)}/{len(rs)}" if rs else "",
            mean_duration_s=round(statistics.mean(number(r.row["duration_s"]) or 0.0 for r in rs)) if rs else "",
            max_temp_c=round(max(number(r.row["run_temp_max"]) or 0.0 for r in rs)) if rs else "",
            current_a=round(statistics.mean(currents), 2) if currents else "",
            each_run=" ".join(f"{number(r.row['turns']) or 0:.1f}{'' if r.row['outcome'] == 'completed' else 'd'}"
                              for r in rs),
            sessions=" ".join(sorted({r.session.name[5:] for r in rs})),
            wandb=m.get("wandb", {}).get("path", "")))
    table.sort(key=lambda t: (t["runs"] == 0, -(t["mean_turns"] or 0)))

    with open(root / "overview.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(table[0]))
        w.writeheader()
        w.writerows(table)

    lines = [
        "# Model overview (real hand)", "",
        "Generated by `experiments/rl_inference/real_eval/overview.py` (rwr_system) from every session's results.csv; "
        "`overview.csv` has the same table, the W&B project `rwr-skin/real_hand_eval` the runs.", "",
        f"**Comparable runs**: saved, at the model's own goal speed, every motor below {MAX_START_C} C at the start: "
        "60 s, 45 mm cube, auto exposure, wrist start +30 deg, abort at 58 C. A run ends early when "
        "the cube drops (`d` after the turns) or is lost. One run can differ a lot from the next: rank by the mean "
        "only where there are 2+ runs.", "",
        "| # | model | what it is | runs | mean turns | spread | best | worst | full 60 s | max C | each run |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for i, t in enumerate(table, 1):
        if t["runs"]:
            lines.append(f"| {i} | {t['model']} | {t['description']} | {t['runs']} | **{t['mean_turns']}** | "
                         f"{t['std_turns']} | {t['best_turns']} | {t['worst_turns']} | {t['full_60s']} | "
                         f"{t['max_temp_c']} | {t['each_run']} |")
    untested = [t["model"] for t in table if not t["runs"]]
    if untested:
        lines += ["", "No comparable run: " + ", ".join(untested)]
    other = [r for r in runs if not r.comparable]
    lines += ["", "## Saved runs not in the comparison", "", "| model | turns | outcome | why not | session |",
              "|---|---|---|---|---|"]
    for r in sorted(other, key=lambda r: r.model):
        lines.append(f"| {r.model} | {number(r.row['turns']) or 0:.1f} | {r.row['outcome']} | "
                     f"{r.not_comparable_because} | {r.session.name} |")
    (root / "OVERVIEW.md").write_text("\n".join(lines) + "\n")
    print(f"wrote {root / 'OVERVIEW.md'} and overview.csv: {sum(t['runs'] for t in table)} comparable runs of "
          f"{sum(1 for t in table if t['runs'])} models, {len(other)} other saved runs")


if __name__ == "__main__":
    main()
